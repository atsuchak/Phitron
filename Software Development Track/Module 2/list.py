number = [3, 2, 5, 2, 76, 34, 23, 56]

print(number[3], number[-4])

print(number[2:6])  #print from index 2 to 6

print(number[2:6:2])  #print from index 2 to 6 with 2 steps gap

print(number[6:2:-1])  #print from index 6 to 2
print(number[6:2:-2])  #print from index 6 to 2 with 2 steps gap


print(number[2: ])  #print from index 2 to last ldx
print(number[ :8])  #print from index 0 to 8 ldx
print(number[ : ])  #print from index 0 to last ldx
print(number[ : : -1])  #print from index last to 0th ldx(reverse array)

